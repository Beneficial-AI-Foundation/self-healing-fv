class Miner:
    def __init__(self, git: Git, cfg: dict):
        self.git, self.cfg = git, cfg

    def classify(self, path: str, head: str = "") -> str:
        """Class of a file from the config globs, falling back to its content (`head`: the first
        bytes of either version), so that extraction files are recognized wherever a repo kept
        them over its history (SPQR moved them twice)."""
        c = self.cfg
        if matches(path, c["extraction"]):
            return "extraction"
        if matches(path, c["external"]):
            return "external"
        if path.endswith(".lean"):
            name = path.rsplit("/", 1)[-1]
            if head.startswith(AENEAS_HEADER):
                kind = head.split("\n", 2)[1] if "\n" in head else ""
                if "_Template" in name:
                    return "extraction_config"
                if "External" in name or "external" in kind:
                    return "external"  # hand-maintained, even if it kept the generated header
                return "extraction"
            if re.fullmatch(r"(Funs|Types)External\.lean", name):
                return "external"
        if matches(path, c["toolchain"]):
            return "toolchain"
        if matches(path, c["extraction_config"]):
            return "extraction_config"
        if matches(path, c["rust"]):
            return "rust"
        if path.endswith(".lean") and any(path.startswith(r) for r in c["proof_roots"]):
            return "proof"
        return "other"

    def files_by_class(self, parent, sha) -> dict[str, list[dict]]:
        groups: dict[str, list[dict]] = {}
        for f in self.git.changed_files(parent, sha):
            head = (self.git.blob_head(f.get("new_blob")) or self.git.blob_head(f.get("old_blob"))
                    if f["path"].endswith(".lean") else "")
            groups.setdefault(self.classify(f["path"], head), []).append(f)
        return groups

    def lean_diff(self, parent, sha, files: list[dict]) -> dict:
        """Declaration-level diff across a set of changed Lean files. Keys are "path::name"
        (short names repeat across files) with the path *before* the change: the broken state
        keeps the base layout, so a renamed file's theorems must match it (SPQR #287 and dalek
        #865 renamed Aux/ to Auxiliary/). A theorem moved to another file is removed + added."""
        before, after = {}, {}
        new_text, context_changed_files = {}, set()
        for f in files:
            base = f["old_path"]
            old_src = self.git.show(parent, base) if parent else None
            if old_src is not None and context_lines(old_src) != context_lines(self.git.show(sha, f["path"])):
                context_changed_files.add(base)
            for k, v in parse_decls(old_src).items():
                before[f"{base}::{k}"] = dict(v, file=base)
            new_text[base] = self.git.show(sha, f["path"]) or ""
            for k, v in parse_decls(new_text[base]).items():
                after[f"{base}::{k}"] = dict(v, file=f["path"])
        d = diff_decls(before, after)
        # A theorem that disappeared from code but whose name still appears in its file's
        # new text (i.e. inside a comment) was most likely commented out rather than deleted.
        def commented(key):
            path, name = key.split("::", 1)
            return re.search(rf"\b(theorem|lemma)\s+{re.escape(name)}(?![\w.'])", new_text.get(path, ""))
        d["commented_out"] = [k for k in d["removed"]
                              if before[k]["kind"] in ("theorem", "lemma") and commented(k)]
        # Theorems whose text is unchanged but whose file's namespace/open context changed: the
        # same text may now resolve to different names (e.g. Aeneas moved `sub` into a namespace).
        d["context_changed"] = sorted(k for k in set(before) & set(after)
                                      if k.split("::", 1)[0] in context_changed_files
                                      and k not in d["statement_changed"] and k not in d["body_changed"])
        d["sorry_before"] = sum(v["sorry"] for v in before.values())
        d["sorry_after"] = sum(v["sorry"] for v in after.values())
        d["axioms_added"] = [n for n in d["added"] if after[n]["kind"] in ("axiom", "opaque")]
        d["sorry_added_in"] = sorted(n for n, v in after.items() if v["sorry"] > before.get(n, {}).get("sorry", 0))
        d["sorry_removed_in"] = sorted(n for n, v in before.items() if v["sorry"] > after.get(n, {}).get("sorry", 0))
        d["_before"], d["_after"] = before, after
        return d

    def proof_summary(self, parent, sha, files, changed_extraction: list[str] | None = None) -> dict:
        d = self.lean_diff(parent, sha, files)
        before, after = d.pop("_before"), d.pop("_after")
        deleted_files = {f["path"] for f in files if f.get("status") == "D"}
        thm = lambda n, side: side.get(n, {}).get("kind") in ("theorem", "lemma")
        # Short names (last component) of extracted defs this change modified or removed.
        short = {k.split("::", 1)[1].rsplit(".", 1)[-1] for k in changed_extraction or []}
        short = {n for n in short if not n.startswith("<")}
        refs = lambda n: n in before and bool(short) and bool(set(re.findall(r"[\w']+", before[n]["statement"] + " " + before[n]["body"])) & short)
        existing_touched = sorted({n for n in d["statement_changed"] + d["body_changed"] + d["header_changed"]
                                   if thm(n, before)})
        return {
            "files_changed": len(files),
            "lines_added": sum(f.get("added", 0) for f in files),
            "lines_removed": sum(f.get("removed", 0) for f in files),
            "theorems_touched": cap(sorted(existing_touched)),
            "theorems_touched_n": len(existing_touched),
            "statements_changed": [
                {"name": n, "file": after[n]["file"],
                 "before": before[n]["statement"][:MAX_TEXT], "after": after[n]["statement"][:MAX_TEXT]}
                for n in d["statement_changed"] if thm(n, before)
            ],
            "statements_changed_n": sum(1 for n in d["statement_changed"] if thm(n, before)),
            "defs_statement_changed_n": sum(1 for n in d["statement_changed"] if not thm(n, before)),
            "theorem_headers_changed_n": sum(1 for n in d["header_changed"] if thm(n, before)),
            "theorems_removed": cap([n for n in d["removed"] if thm(n, before)]),
            # Replays: deleted theorems that mention changed extracted code were usually broken
            # (e.g. merged into a new spec); others were cleanup.
            "theorems_removed_referencing_extraction": cap([n for n in d["removed"] if thm(n, before) and refs(n)]),
            # Project declarations placed in a library namespace clash when the library adds the
            # same name; the fix deletes them (replays: #638).
            # Full name = enclosing namespace + name (SPQR #238 declares `next_Usize_spec`
            # inside `namespace Aeneas.Std...`; dalek #638 spells the prefix in the name).
            # Only from files that survive the change: deleting a whole file of library-namespace
            # helpers is cleanup (dalek #535 mvcgen.lean), not a clash fix.
            "removed_in_library_namespace": cap([n for n in d["removed"]
                                                 if n.split("::", 1)[0] not in deleted_files
                                                 and re.match(r"(Aeneas|Std|Mathlib)\.",
                                                             ".".join(x for x in (before[n].get("namespace"),
                                                                                  n.split("::", 1)[1]) if x))]),
            "theorems_touched_referencing_extraction_n": sum(1 for n in existing_touched if refs(n)),
            # Every changed declaration in these files that mentions changed extracted code.
            "decls_referencing_extraction": sorted(n for n in set(before) & (
                set(d["statement_changed"]) | set(d["body_changed"]) | set(d["header_changed"])
                | set(d["removed"]) | set(d["context_changed"]) | set(d["sorry_added_in"])) if refs(n)),
            "theorems_removed_n": sum(1 for n in d["removed"] if thm(n, before)),
            "theorems_commented_out": cap(d["commented_out"]),
            "theorems_context_changed": cap([n for n in d["context_changed"] if thm(n, before)]),
            # Hand-written defs in spec/proof files edited by the fix (they break too, e.g. when
            # an extracted name they mention is renamed).
            "defs_touched": cap(sorted(n for n in d["statement_changed"] + d["body_changed"]
                                       if not thm(n, before) and before[n]["kind"] in ("def", "abbrev"))),
            "theorems_added_n": sum(1 for n in d["added"] if thm(n, after)),
            "sorry_delta": d["sorry_after"] - d["sorry_before"],
            "sorry_added_in": cap(d["sorry_added_in"]),
            "sorry_removed_in": cap(d["sorry_removed_in"]),
            "axioms_added": d["axioms_added"],
        }

    def extraction_summary(self, parent, sha, files) -> dict:
        d = self.lean_diff(parent, sha, files)
        d.pop("_before"); d.pop("_after")
        modified = sorted(set(d["statement_changed"] + d["body_changed"] + d["header_changed"]))
        return {
            "files": [f["path"] for f in files],
            "lines_added": sum(f.get("added", 0) for f in files),
            "lines_removed": sum(f.get("removed", 0) for f in files),
            "defs_added_n": len(d["added"]),
            "defs_removed_n": len(d["removed"]),
            "defs_signature_changed_n": len(d["statement_changed"]),
            "defs_body_changed_n": len(d["body_changed"]),
            "defs_modified": cap(sorted(modified)),
            "defs_removed": cap(d["removed"]),
            "only_additions": not modified and not d["removed"],
            # Diff touches only comments/whitespace (e.g. doc-comment reformatting by a new Aeneas).
            "comment_only": not (modified or d["removed"] or d["added"]),
        }


def cap(xs: list) -> list:
    return xs if len(xs) <= MAX_LIST else xs[:MAX_LIST] + [f"... (+{len(xs) - MAX_LIST} more)"]


def pr_number(subject: str) -> int | None:
    """PR number from a squash-merge subject `... (#123)` or a merge `Merge pull request #123 ...`."""
    m = re.search(r"\(#(\d+)\)\s*$", subject) or re.match(r"Merge pull request #(\d+)", subject)
    return int(m.group(1)) if m else None


def days_between(a: str, b: str) -> float:
    parse = lambda d: datetime.fromisoformat(d.replace("Z", "+00:00"))  # py3.9 lacks 'Z'
    return abs((parse(b) - parse(a)).total_seconds()) / 86400


def change_causes(git: Git, miner: Miner, cfg: dict, parent: str, sha: str,
                  groups: dict[str, list[dict]] | None = None) -> tuple[dict, dict | None, list[str]]:
    """(pin_changes, extraction summary, cause labels) of the change parent → sha, from the pin
    and toolchain diff and the changed file classes. Mining and live runs share this rule."""
    groups = miner.files_by_class(parent, sha) if groups is None else groups
    aeneas = cfg["aeneas_package"]
    core = {aeneas, "lean", *cfg["core_packages"]}
    pins_before, pins_after = toolchain_pins(git, parent, cfg), toolchain_pins(git, sha, cfg)
    pin_changes = {k: [pins_before.get(k), pins_after.get(k)]
                   for k in sorted(set(pins_before) | set(pins_after))
                   if pins_before.get(k) != pins_after.get(k)}
    extraction = miner.extraction_summary(parent, sha, groups["extraction"]) if "extraction" in groups else None
    causes = []
    if aeneas in pin_changes:
        causes.append("aeneas")
    if (core - {aeneas}) & set(pin_changes):
        causes.append("lean-mathlib")
    if extraction and not extraction["comment_only"] and "rust" in groups:
        causes.append("rust")
    if set(pin_changes) - core:
        causes.append("lean-dep")  # other lake dependency, e.g. PrimeCert
    if "extraction" in groups and not causes:
        # Re-extraction without a Rust or pin change: new functions extracted, config change...
        causes.append("extraction-config" if "extraction_config" in groups else "extraction-only")
    return pin_changes, extraction, causes


def mine(repo: Path, cfg_name: str, rev: str | None) -> list[dict]:
    cfg = REPO_CONFIGS[cfg_name]
    git = Git(repo)
    miner = Miner(git, cfg)
    rev = rev or cfg["rev"] or "origin/HEAD"
    aeneas = cfg["aeneas_package"]
    core = {aeneas, "lean", *cfg["core_packages"]}
    commits = git.first_parent_commits(rev)

    groups_by_sha = {}
    trigger_idx = []
    for i, c in enumerate(commits):
        groups = miner.files_by_class(c["parent"], c["sha"])
        groups_by_sha[c["sha"]] = groups
        if c["parent"] is None:
            continue  # root commit: nothing to break
        if "extraction" in groups or ("toolchain" in groups and
                                      toolchain_pins(git, c["parent"], cfg) != toolchain_pins(git, c["sha"], cfg)):
            trigger_idx.append(i)

    records = []
    for t_pos, i in enumerate(trigger_idx):
        c = commits[i]
        groups = groups_by_sha[c["sha"]]
        pin_changes, extraction, causes = change_causes(git, miner, cfg, c["parent"], c["sha"], groups)

        external_files = groups.get("external", [])
        changed_extraction = (extraction["defs_modified"] + extraction["defs_removed"]) if extraction else []
        proofs_in_change = miner.proof_summary(c["parent"], c["sha"], groups["proof"], changed_extraction) \
            if "proof" in groups else None

        # Follow-up fixes: commits after the trigger, before the next trigger, within limits.
        end = trigger_idx[t_pos + 1] if t_pos + 1 < len(trigger_idx) else len(commits)
        followups = []
        removed_by_change = set(proofs_in_change["theorems_removed"]) if proofs_in_change else set()
        sorry_by_change = set(proofs_in_change["sorry_added_in"]) if proofs_in_change else set()
        for j in range(i + 1, min(end, i + 1 + FOLLOWUP_MAX_COMMITS)):
            f = commits[j]
            if days_between(c["date"], f["date"]) > FOLLOWUP_MAX_DAYS:
                break
            fg = groups_by_sha[f["sha"]]
            if "proof" not in fg:
                continue
            reasons = []
            if FIX_MSG_RE.search(f["subject"]):
                reasons.append("message")
            ps = None
            if removed_by_change or sorry_by_change:
                ps = miner.proof_summary(f["parent"], f["sha"], fg["proof"])
                restored = removed_by_change & set(miner.lean_diff(f["parent"], f["sha"], fg["proof"])["added"])
                if restored:
                    reasons.append(f"restores {len(restored)} theorem(s) removed by change")
                cleared = sorry_by_change & set(ps["sorry_removed_in"])
                if cleared:
                    reasons.append(f"removes sorry from {len(cleared)} theorem(s) sorried by change")
            if reasons == ["message"] and not any(git.show(c["sha"], p["path"]) is not None for p in fg["proof"]):
                # A "fix" that edits only proof files created after the trigger cannot repair what
                # the trigger broke (libsignal-verify PR 39, a model fix in files PRs 22-37 added).
                continue
            if reasons:
                ps = ps or miner.proof_summary(f["parent"], f["sha"], fg["proof"])
                followups.append({
                    "sha": f["sha"], "date": f["date"], "subject": f["subject"],
                    "pr": pr_number(f["subject"]), "reasons": reasons,
                    "proofs": {k: ps[k] for k in ("files_changed", "lines_added", "lines_removed",
                                                  "theorems_touched_n", "statements_changed_n",
                                                  "sorry_delta")},
                    "statements_changed": [s["name"] for s in ps["statements_changed"]],
                })

        fix_in_change = bool(proofs_in_change and (proofs_in_change["theorems_touched_n"]
                                                   or proofs_in_change["theorems_removed_n"]))
        stmt_names = [s["name"] for s in (proofs_in_change or {}).get("statements_changed", [])]
        for fu in followups:
            stmt_names += fu["statements_changed"]
        extraction_modifies = bool(extraction and not extraction["only_additions"])
        pc = proofs_in_change or {}
        heuristic = sorted(set(
            pc.get("theorems_touched", []) + pc.get("theorems_commented_out", [])
            + pc.get("theorems_removed_referencing_extraction", []) + pc.get("defs_touched", [])
            + pc.get("sorry_added_in", []) + pc.get("theorems_context_changed", [])
            + (pc.get("removed_in_library_namespace", []) if aeneas in pin_changes else [])
        ) - {""})
        core_pin_change = bool(core & set(pin_changes))
        if proofs_in_change and not core_pin_change:
            # No pin change: only the extracted code changed, so (replays: #445) only declarations
            # that mention a changed extracted definition can break.
            heuristic = [n for n in heuristic if n in set(pc.get("decls_referencing_extraction", []))]
        pr = pr_number(c["subject"])

        records.append({
            "case_id": f"{cfg_name}/{c['sha'][:8]}",
            "repo": cfg["github"],
            "base_commit": c["parent"],
            "change_commit": c["sha"],
            "change_date": c["date"],
            "change_subject": c["subject"],
            "change_pr": pr,
            "change_pr_url": f"https://github.com/{cfg['github']}/pull/{pr}" if pr else None,
            "cause": causes[0],
            "causes": causes,
            "pin_changes": pin_changes,
            "files_changed_by_class": {k: len(v) for k, v in sorted(groups.items())},
            "extraction": extraction,
            "external_changed": [f["path"] for f in external_files],
            "rust_files_changed_n": len(groups.get("rust", [])),
            "fix": {
                "in_change_commit": fix_in_change,
                "fix_commits": ([c["sha"]] if fix_in_change else []) + [fu["sha"] for fu in followups],
                "followups": followups,
            },
            "proofs_in_change_commit": proofs_in_change,
            # Heuristic: existing theorems the human edited, removed, or sorried while fixing.
            "broken_theorems_heuristic": cap(heuristic),
            "statements_changed_by_fix": bool(stmt_names),
            "statements_changed_by_fix_n": len(stmt_names),
            "size": {
                "extraction_lines": (extraction["lines_added"] + extraction["lines_removed"]) if extraction else 0,
                "proof_lines": ((proofs_in_change["lines_added"] + proofs_in_change["lines_removed"])
                                if proofs_in_change else 0)
                               + sum(fu["proofs"]["lines_added"] + fu["proofs"]["lines_removed"] for fu in followups),
                "theorems_touched": ((proofs_in_change or {}).get("theorems_touched_n", 0)
                                     + sum(fu["proofs"]["theorems_touched_n"] for fu in followups)),
            },
            # Worth replaying: something the proofs depend on changed and humans edited proofs.
            "likely_break": bool((core_pin_change and (fix_in_change or followups)) or
                                 (extraction_modifies and proofs_in_change and
                                  heuristic)),
            "mined_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        })
    return records


def check_config(git: Git, cfg: dict, rev: str) -> list[tuple[str, str]]:
    """Sanity-check a config against the repo at `rev`: (level, message) pairs, level ERROR/WARN/OK."""
    out = []
    try:
        files = git.run("ls-tree", "-r", "--name-only", rev).splitlines()
    except subprocess.CalledProcessError:
        return [("ERROR", f"cannot read {rev}; set 'rev' to an existing branch (e.g. origin/main)")]
    out.append(("OK", f"{rev}: {len(files)} files, {git.run('rev-list', '--first-parent', '--count', rev).strip()} "
                      f"first-parent commits, {git.run('rev-list', '--first-parent', '--merges', '--count', rev).strip()} merges"))
    present = set(files)
    for f in ("lean-toolchain", "lake-manifest.json"):
        level = "OK" if lean_path(cfg, f) in present else "ERROR"
        out.append((level, f"{lean_path(cfg, f)} {'found' if level == 'OK' else 'missing: check lean_root'}"))
    lakefiles = [lean_path(cfg, f) for f in ("lakefile.toml", "lakefile.lean") if lean_path(cfg, f) in present]
    out.append(("OK" if lakefiles else "ERROR", f"lakefile: {lakefiles or 'none under lean_root'}"))
    manifest = git.show(rev, lean_path(cfg, "lake-manifest.json"))
    names = [p.get("name") for p in json.loads(manifest).get("packages", [])] if manifest else []
    pins = toolchain_pins(git, rev, cfg)
    for pkg in [cfg["aeneas_package"], *cfg["core_packages"]]:
        rev_ = pins.get(pkg)
        hint = " (path dependency? set aeneas_pin)" if pkg == cfg["aeneas_package"] and pkg in names else ""
        out.append(("OK" if rev_ else "WARN", f"package {pkg!r}: {rev_ or 'no pinned rev' + hint}"))
    out.append(("OK" if pins.get("lean") else "ERROR", f"lean toolchain: {pins.get('lean')}"))
    for key, required in (("extraction", True), ("external", False), ("extraction_config", False),
                          ("rust", False)):
        hits = [f for f in files if matches(f, cfg[key])]
        level = "OK" if hits else ("ERROR" if required else "WARN")
        out.append((level, f"{key}: {len(hits)} file(s) {hits[:4]}{' ...' if len(hits) > 4 else ''}"))
    proofs = [f for f in files if f.endswith(".lean") and any(f.startswith(r) for r in cfg["proof_roots"])
              and not matches(f, cfg["extraction"] + cfg["external"])]
    out.append(("OK" if proofs else "ERROR", f"proof files under {cfg['proof_roots']}: {len(proofs)}"))
    lean_files = [f for f in files if f.endswith(".lean") and (not cfg["lean_root"] or f.startswith(cfg["lean_root"] + "/"))]
    unclassified = [f for f in lean_files if f not in proofs and not matches(f, cfg["extraction"] + cfg["external"])]
    if unclassified:
        out.append(("WARN", f"{len(unclassified)} .lean file(s) in no class (ignored), e.g. {unclassified[:3]}"))
    libs = lean_libs(git.show(rev, lean_path(cfg, "lakefile.toml")), git.show(rev, lean_path(cfg, "lakefile.lean")))
    out.append(("OK" if libs else "WARN", f"lean_libs (name, srcDir): {libs or 'none parsed; modules = file paths'}"))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True, choices=sorted(REPO_CONFIGS))
    ap.add_argument("--repo", required=True, type=Path, help="path to an existing local clone")
    ap.add_argument("--rev", help="history to walk (default: the config's rev)")
    ap.add_argument("--out", type=Path, help="JSONL output path (default: stdout)")
    ap.add_argument("--check", action="store_true", help="validate the config against the repo and exit")
    args = ap.parse_args()

    if args.check:
        cfg = REPO_CONFIGS[args.config]
        report = check_config(Git(args.repo.expanduser()), cfg, args.rev or cfg["rev"] or "origin/HEAD")
        for level, msg in report:
            print(f"{level:5} {msg}")
        return 1 if any(level == "ERROR" for level, _ in report) else 0

    records = mine(args.repo.expanduser(), args.config, args.rev)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.out.with_suffix(args.out.suffix + ".tmp") if args.out else None
    out = open(tmp, "w") if tmp else sys.stdout
    try:
        for r in records:
            out.write(json.dumps(r, ensure_ascii=False) + "\n")
    finally:
        if tmp:
            out.close()
            tmp.replace(args.out)  # atomic: readers never see a partial file
    n_likely = sum(r["likely_break"] for r in records)
    print(f"{len(records)} trigger commits, {n_likely} likely breaks -> {args.out or 'stdout'}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

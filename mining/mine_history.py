CONFIG_FILE = Path(__file__).resolve().parent / "repos.json"
CONFIG_DEFAULTS = {
    "rev": None,              # history to walk; None = the clone's origin/HEAD (default branch)
    "lean_root": "",          # directory of the Lake project (lakefile, lean-toolchain), "" = repo root
    "aeneas_package": "aeneas",   # lake-manifest name of the Aeneas Lean library
    "core_packages": ["mathlib"],  # other pins whose change counts as a toolchain bump
    "extraction": [],         # Aeneas-generated Lean code the proofs are about
    "external": [],           # hand-maintained models of external functions/types (trusted)
    "extraction_config": [],  # extraction settings (aeneas config, function lists, workflows)
    "rust": [],               # Rust sources
    "proof_roots": [],        # every other .lean file under these prefixes is a spec/proof file
    # When Aeneas is a path dependency (no rev in lake-manifest), where the Aeneas commit is
    # recorded instead: {"file": repo-relative path, "regex": pattern with one capture group}.
    "aeneas_pin": None,
}


def load_configs(path: Path = CONFIG_FILE) -> dict[str, dict]:
    """Per-repo layouts from repos.json, with defaults filled in and derived toolchain paths."""
    raw = json.loads(path.read_text())
    configs = {}
    for name, entry in raw.items():
        if name.startswith("_"):
            continue
        cfg = {**CONFIG_DEFAULTS, **{k: v for k, v in entry.items() if not k.startswith("_")}}
        root = cfg["lean_root"].strip("/")
        cfg["lean_root"] = root
        cfg.setdefault("toolchain", [lean_path(cfg, f) for f in
                                     ("lean-toolchain", "lakefile.toml", "lakefile.lean", "lake-manifest.json")]
                       + ([cfg["aeneas_pin"]["file"]] if cfg["aeneas_pin"] else []))
        configs[name] = cfg
    return configs


def lean_path(cfg: dict, rel: str) -> str:
    """Repo-relative path of a file given relative to the Lake project root."""
    return f"{cfg['lean_root']}/{rel}" if cfg["lean_root"] else rel



#!/usr/bin/env python3
"""Mine candidate proof-break cases from the git history of a verified-Rust repo (SCI-1714).

Read-only: uses git plumbing (`git log`, `git show`, `git diff`) against an existing local
clone. It never checks out, fetches, or writes inside the target repo.

A *trigger* is a first-parent commit that changes the extracted Lean code (e.g. Funs.lean /
Types.lean) or the Lean/Aeneas toolchain pin (lean-toolchain, lakefile, lake-manifest.json).
For each trigger we look for the human *fix*: proof edits in the trigger commit itself
(common in squash-merged repos) and follow-up commits before the next trigger that look like
repairs. Output is one JSON object per trigger (JSON Lines).

Theorem-level fields ("touched", "statement_changed", ...) come from a comment-aware textual
parse of Lean declarations, not from elaboration; treat them as heuristics until a replay
build confirms which theorems actually break.

Usage:
  python3 mining/mine_history.py --config dalek-lean-verify \
      --repo ~/baif/curve25519-dalek-lean-verify --out data/raw/dalek-lean-verify.jsonl
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

# Per-repo layout. Globs use fnmatch semantics ('*' also matches '/').
REPO_CONFIGS = {
    "dalek-lean-verify": {
        "github": "Beneficial-AI-Foundation/curve25519-dalek-lean-verify",
        "rev": "origin/master",
        # Generated by Aeneas; the code the proofs are about.
        "extraction": ["Curve25519Dalek/Funs.lean", "Curve25519Dalek/Types.lean"],
        # Hand-maintained models of external functions/types: part of the trusted base.
        "external": ["Curve25519Dalek/FunsExternal.lean", "Curve25519Dalek/TypesExternal.lean"],
        "toolchain": ["lean-toolchain", "lakefile.toml", "lakefile.lean", "lake-manifest.json"],
        "extraction_config": ["aeneas-config.yml", "functions.json", ".github/workflows/aeneas-extract.yml"],
        "rust": ["curve25519-dalek/*.rs", "curve25519-dalek/*Cargo.toml", "src-modifications.diff"],
        # Every other tracked .lean file under these prefixes is treated as specs/proofs.
        "proof_roots": ["Curve25519Dalek/", "Utils/"],
    },
}

FOLLOWUP_MAX_COMMITS = 15
FOLLOWUP_MAX_DAYS = 30
FIX_MSG_RE = re.compile(
    r"\b(fix\w*|repair\w*|broke\w*|breakage|restor\w*|re-?enable\w*|uncomment\w*|mend\w*|"
    r"after (the )?(aeneas|lean|mathlib|toolchain) (update|bump)|sorry)\b",
    re.IGNORECASE,
)
MAX_TEXT = 800  # truncate statement text in output
MAX_LIST = 500  # truncate long name lists in output


# ---------------------------------------------------------------- git helpers

class Git:
    def __init__(self, repo: Path):
        self.repo = repo
        self._blob_cache: dict[tuple[str, str], str | None] = {}

    def run(self, *args: str) -> str:
        out = subprocess.run(
            ["git", "-C", str(self.repo), *args],
            check=True, capture_output=True, text=True, errors="replace",
        )
        return out.stdout

    def show(self, rev: str, path: str) -> str | None:
        key = (rev, path)
        if key not in self._blob_cache:
            try:
                self._blob_cache[key] = self.run("show", f"{rev}:{path}")
            except subprocess.CalledProcessError:
                self._blob_cache[key] = None  # file absent at rev
        return self._blob_cache[key]

    def first_parent_commits(self, rev: str) -> list[dict]:
        sep = "\x1f"
        fmt = sep.join(["%H", "%P", "%aI", "%an", "%s"])
        rows = []
        for line in self.run("log", "--first-parent", "--reverse", f"--format={fmt}", rev).splitlines():
            sha, parents, date, author, subject = line.split(sep, 4)
            rows.append({
                "sha": sha, "parent": parents.split()[0] if parents else None,
                "date": date, "author": author, "subject": subject,
            })
        return rows

    def body(self, sha: str) -> str:
        return self.run("log", "-1", "--format=%b", sha)

    def changed_files(self, parent: str | None, sha: str) -> list[dict]:
        """Name-status + numstat for parent..sha (with rename detection)."""
        if parent is None:
            parent = self.run("hash-object", "-t", "tree", "/dev/null").strip()  # empty tree
        status = {}
        for line in self.run("diff", "--name-status", "-M", parent, sha).splitlines():
            parts = line.split("\t")
            code = parts[0]
            if code.startswith("R"):
                status[parts[2]] = {"status": "R", "old_path": parts[1], "path": parts[2]}
            else:
                status[parts[1]] = {"status": code, "old_path": parts[1], "path": parts[1]}
        for line in self.run("diff", "--numstat", "-M", parent, sha).splitlines():
            added, removed, path = line.split("\t", 2)
            if " => " in path:  # rename syntax: a/{x => y}/b or x => y
                m = re.match(r"(.*)\{(.*) => (.*)\}(.*)", path)
                path = (m.group(1) + m.group(3) + m.group(4)).replace("//", "/") if m else path.split(" => ")[1]
            entry = status.setdefault(path, {"status": "?", "old_path": path, "path": path})
            entry["added"] = int(added) if added != "-" else 0
            entry["removed"] = int(removed) if removed != "-" else 0
        return list(status.values())


def matches(path: str, globs: list[str]) -> bool:
    return any(fnmatch.fnmatch(path, g) for g in globs)


# ---------------------------------------------------------------- Lean parsing

def strip_comments(src: str) -> str:
    """Blank out Lean comments (nested block comments, line comments), keeping newlines."""
    out = []
    i, n, depth, in_str = 0, len(src), 0, False
    while i < n:
        c, nxt = src[i], src[i + 1] if i + 1 < n else ""
        if depth:
            if c == "/" and nxt == "-":
                depth += 1; out.append("  "); i += 2; continue
            if c == "-" and nxt == "/":
                depth -= 1; out.append("  "); i += 2; continue
            out.append("\n" if c == "\n" else " "); i += 1; continue
        if in_str:
            out.append(c)
            if c == "\\" and nxt:
                out.append(nxt); i += 2; continue
            if c == '"':
                in_str = False
            i += 1; continue
        if c == '"':
            in_str = True; out.append(c); i += 1; continue
        if c == "/" and nxt == "-":
            depth = 1; out.append("  "); i += 2; continue
        if c == "-" and nxt == "-":
            j = src.find("\n", i)
            j = n if j == -1 else j
            out.append(" " * (j - i)); i = j; continue
        out.append(c); i += 1
    return "".join(out)


DECL_RE = re.compile(
    r"^[ \t]*(?:@\[[^\]]*\][ \t]*)*"
    r"(?:(?:private|protected|noncomputable|partial|unsafe|nonrec)[ \t]+)*"
    r"(theorem|lemma|def|abbrev|instance|axiom|opaque|structure|inductive|class)\b[ \t]*"
    r"([^\s:({\[⦃]*)"
)
# Lines that end the previous declaration even though they are not declarations.
BOUNDARY_RE = re.compile(
    r"^(@\[|set_option\b|namespace\b|end\b|section\b|noncomputable section|open\b|variable\b|"
    r"attribute\b|#|universe\b|mutual\b|import\b)"
)
OPEN = "([{⦃⟨"
CLOSE = ")]}⦄⟩"


def split_statement(text: str) -> tuple[str, str]:
    """Split a declaration into (statement, body) at the first top-level ':=' / '|' / 'where'."""
    depth = 0
    i = 0
    while i < len(text):
        c = text[i]
        if c in OPEN:
            depth += 1
        elif c in CLOSE:
            depth = max(0, depth - 1)
        elif depth == 0:
            if text.startswith(":=", i):
                return text[:i], text[i:]
            if c == "|" and (i == 0 or text[i - 1] == "\n" or text[:i].rstrip(" \t").endswith("\n")):
                return text[:i], text[i:]
            if text.startswith("where", i) and (i == 0 or not text[i - 1].isalnum()) and \
                    (i + 5 == len(text) or not (text[i + 5].isalnum() or text[i + 5] in "_'.")):
                return text[:i], text[i:]
        i += 1
    return text, ""


def norm(s: str) -> str:
    return " ".join(s.split())


def split_header(stmt: str) -> tuple[str, str]:
    """Split leading `@[...]` attributes and `set_option ... in` off a normalized statement."""
    i = 0
    while True:
        rest = stmt[i:]
        m = re.match(r"set_option \S+ \S+ in ", rest)
        if m:
            i += m.end(); continue
        if rest.startswith("@["):
            depth, j, in_str = 0, 0, False
            while j < len(rest):
                ch = rest[j]
                if ch == '"':
                    in_str = not in_str
                elif not in_str and ch == "[":
                    depth += 1
                elif not in_str and ch == "]":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            i += j + 1
            while i < len(stmt) and stmt[i] == " ":
                i += 1
            continue
        return stmt[:i].strip(), stmt[i:]


def parse_decls(src: str | None) -> dict[str, dict]:
    """Map declaration name -> {kind, header, statement, body, sorry, start/body_start/end offsets,
    line/body_line/end_line (1-indexed)} from Lean source (comments ignored). Offsets index the
    original source, since comment stripping preserves length."""
    if src is None:
        return {}
    lines = strip_comments(src).split("\n")
    offsets, off = [], 0
    for line in lines:
        offsets.append(off); off += len(line) + 1
    decls: dict[str, dict] = {}
    cur = None

    def close():
        if cur is None:
            return
        idx = cur["idx"]
        while len(idx) > 1 and not lines[idx[-1]].strip():
            idx = idx[:-1]  # drop trailing blank lines
        text = "\n".join(lines[i] for i in idx)
        stmt, body = split_statement(text)
        name = cur["name"] or f"<{cur['kind']}>:{norm(stmt)[:80]}"
        key = name
        k = 2
        while key in decls:  # duplicate short names (e.g. in different namespaces)
            key = f"{name}#{k}"; k += 1
        header, statement = split_header(norm(stmt))
        start = offsets[idx[0]]
        decls[key] = {
            "kind": cur["kind"], "header": header, "statement": statement, "body": norm(body),
            "sorry": len(re.findall(r"\b(sorry|admit)\b", text)),
            "start": start, "body_start": start + len(stmt), "end": start + len(text),
            "line": idx[0] + 1, "body_line": idx[0] + 1 + stmt.count("\n"), "end_line": idx[-1] + 1,
        }

    pending: list[int] = []  # attribute / `set_option ... in` lines preceding a declaration
    for i, line in enumerate(lines):
        m = DECL_RE.match(line)
        if m:
            close()
            cur = {"kind": m.group(1), "name": m.group(2), "idx": pending + [i]}
            pending = []
        elif line[:1] not in (" ", "\t", "") and BOUNDARY_RE.match(line):
            close(); cur = None
            prefix = line.startswith("@[") or re.match(r"set_option\b.*\bin\s*$", line)
            pending = pending + [i] if prefix else []
        elif cur is not None:
            cur["idx"].append(i)
        elif pending:
            pending.append(i)  # continuation of a multi-line attribute, or a blank/comment line
    close()
    return decls


def diff_decls(before: dict, after: dict) -> dict:
    added = sorted(set(after) - set(before))
    removed = sorted(set(before) - set(after))
    stmt_changed, body_changed, header_changed = [], [], []
    for name in sorted(set(before) & set(after)):
        b, a = before[name], after[name]
        if b["statement"] != a["statement"]:
            stmt_changed.append(name)
        elif b["body"] != a["body"]:
            body_changed.append(name)
        if b["header"] != a["header"]:
            header_changed.append(name)  # attributes / set_option only, e.g. @[progress] -> @[step]
    return {"added": added, "removed": removed, "statement_changed": stmt_changed,
            "body_changed": body_changed, "header_changed": header_changed}


# ---------------------------------------------------------------- toolchain

def toolchain_pins(git: Git, rev: str | None) -> dict:
    if rev is None:
        return {}
    pins = {}
    tc = git.show(rev, "lean-toolchain")
    if tc is not None:
        pins["lean"] = tc.strip()
    manifest = git.show(rev, "lake-manifest.json")
    if manifest:
        try:
            for pkg in json.loads(manifest).get("packages", []):
                pins[pkg.get("name", "?")] = pkg.get("rev")
        except json.JSONDecodeError:
            pins["lake-manifest.json"] = "<unparseable>"
    return pins


# ---------------------------------------------------------------- analysis

class Miner:
    def __init__(self, git: Git, cfg: dict):
        self.git, self.cfg = git, cfg

    def classify(self, path: str) -> str:
        c = self.cfg
        if matches(path, c["extraction"]):
            return "extraction"
        if matches(path, c["external"]):
            return "external"
        if matches(path, c["toolchain"]):
            return "toolchain"
        if matches(path, c["extraction_config"]):
            return "extraction_config"
        if matches(path, c["rust"]):
            return "rust"
        if path.endswith(".lean") and any(path.startswith(r) for r in c["proof_roots"]):
            return "proof"
        return "other"

    def files_by_class(self, parent, sha) -> dict[str, list[dict]]:
        groups: dict[str, list[dict]] = {}
        for f in self.git.changed_files(parent, sha):
            groups.setdefault(self.classify(f["path"]), []).append(f)
        return groups

    def lean_diff(self, parent, sha, files: list[dict]) -> dict:
        """Declaration-level diff across a set of changed Lean files. Keys are "path::name"
        (short names repeat across files); renamed files keep their keys via the new path,
        while a theorem moved to another file shows up as removed + added."""
        before, after = {}, {}
        new_text = {}
        for f in files:
            for k, v in parse_decls(self.git.show(parent, f["old_path"]) if parent else None).items():
                before[f"{f['path']}::{k}"] = dict(v, file=f["old_path"])
            new_text[f["path"]] = self.git.show(sha, f["path"]) or ""
            for k, v in parse_decls(new_text[f["path"]]).items():
                after[f"{f['path']}::{k}"] = dict(v, file=f["path"])
        d = diff_decls(before, after)
        # A theorem that disappeared from code but whose name still appears in its file's
        # new text (i.e. inside a comment) was most likely commented out rather than deleted.
        def commented(key):
            path, name = key.split("::", 1)
            return re.search(rf"\b(theorem|lemma)\s+{re.escape(name)}(?![\w.'])", new_text.get(path, ""))
        d["commented_out"] = [k for k in d["removed"]
                              if before[k]["kind"] in ("theorem", "lemma") and commented(k)]
        d["sorry_before"] = sum(v["sorry"] for v in before.values())
        d["sorry_after"] = sum(v["sorry"] for v in after.values())
        d["axioms_added"] = [n for n in d["added"] if after[n]["kind"] in ("axiom", "opaque")]
        d["sorry_added_in"] = sorted(n for n, v in after.items() if v["sorry"] > before.get(n, {}).get("sorry", 0))
        d["sorry_removed_in"] = sorted(n for n, v in before.items() if v["sorry"] > after.get(n, {}).get("sorry", 0))
        d["_before"], d["_after"] = before, after
        return d

    def proof_summary(self, parent, sha, files) -> dict:
        d = self.lean_diff(parent, sha, files)
        before, after = d.pop("_before"), d.pop("_after")
        thm = lambda n, side: side.get(n, {}).get("kind") in ("theorem", "lemma")
        existing_touched = sorted({n for n in d["statement_changed"] + d["body_changed"] + d["header_changed"]
                                   if thm(n, before)})
        return {
            "files_changed": len(files),
            "lines_added": sum(f.get("added", 0) for f in files),
            "lines_removed": sum(f.get("removed", 0) for f in files),
            "theorems_touched": cap(sorted(existing_touched)),
            "theorems_touched_n": len(existing_touched),
            "statements_changed": [
                {"name": n, "file": after[n]["file"],
                 "before": before[n]["statement"][:MAX_TEXT], "after": after[n]["statement"][:MAX_TEXT]}
                for n in d["statement_changed"] if thm(n, before)
            ],
            "statements_changed_n": sum(1 for n in d["statement_changed"] if thm(n, before)),
            "defs_statement_changed_n": sum(1 for n in d["statement_changed"] if not thm(n, before)),
            "theorem_headers_changed_n": sum(1 for n in d["header_changed"] if thm(n, before)),
            "theorems_removed": cap([n for n in d["removed"] if thm(n, before)]),
            "theorems_removed_n": sum(1 for n in d["removed"] if thm(n, before)),
            "theorems_commented_out": cap(d["commented_out"]),
            "theorems_added_n": sum(1 for n in d["added"] if thm(n, after)),
            "sorry_delta": d["sorry_after"] - d["sorry_before"],
            "sorry_added_in": cap(d["sorry_added_in"]),
            "sorry_removed_in": cap(d["sorry_removed_in"]),
            "axioms_added": d["axioms_added"],
        }

    def extraction_summary(self, parent, sha, files) -> dict:
        d = self.lean_diff(parent, sha, files)
        d.pop("_before"); d.pop("_after")
        modified = sorted(set(d["statement_changed"] + d["body_changed"] + d["header_changed"]))
        return {
            "files": [f["path"] for f in files],
            "lines_added": sum(f.get("added", 0) for f in files),
            "lines_removed": sum(f.get("removed", 0) for f in files),
            "defs_added_n": len(d["added"]),
            "defs_removed_n": len(d["removed"]),
            "defs_signature_changed_n": len(d["statement_changed"]),
            "defs_body_changed_n": len(d["body_changed"]),
            "defs_modified": cap(sorted(modified)),
            "defs_removed": cap(d["removed"]),
            "only_additions": not modified and not d["removed"],
            # Diff touches only comments/whitespace (e.g. doc-comment reformatting by a new Aeneas).
            "comment_only": not (modified or d["removed"] or d["added"]),
        }


def cap(xs: list) -> list:
    return xs if len(xs) <= MAX_LIST else xs[:MAX_LIST] + [f"... (+{len(xs) - MAX_LIST} more)"]


def pr_number(subject: str) -> int | None:
    m = re.search(r"\(#(\d+)\)\s*$", subject)
    return int(m.group(1)) if m else None


def days_between(a: str, b: str) -> float:
    parse = lambda d: datetime.fromisoformat(d.replace("Z", "+00:00"))  # py3.9 lacks 'Z'
    return abs((parse(b) - parse(a)).total_seconds()) / 86400


def mine(repo: Path, cfg_name: str, rev: str | None) -> list[dict]:
    cfg = REPO_CONFIGS[cfg_name]
    git = Git(repo)
    miner = Miner(git, cfg)
    rev = rev or cfg["rev"]
    commits = git.first_parent_commits(rev)

    groups_by_sha = {}
    trigger_idx = []
    for i, c in enumerate(commits):
        groups = miner.files_by_class(c["parent"], c["sha"])
        groups_by_sha[c["sha"]] = groups
        if c["parent"] is None:
            continue  # root commit: nothing to break
        if "extraction" in groups or ("toolchain" in groups and
                                      toolchain_pins(git, c["parent"]) != toolchain_pins(git, c["sha"])):
            trigger_idx.append(i)

    records = []
    for t_pos, i in enumerate(trigger_idx):
        c = commits[i]
        groups = groups_by_sha[c["sha"]]
        pins_before, pins_after = toolchain_pins(git, c["parent"]), toolchain_pins(git, c["sha"])
        pin_changes = {k: [pins_before.get(k), pins_after.get(k)]
                       for k in sorted(set(pins_before) | set(pins_after))
                       if pins_before.get(k) != pins_after.get(k)}

        extraction = miner.extraction_summary(c["parent"], c["sha"], groups["extraction"]) \
            if "extraction" in groups else None
        causes = []
        if "aeneas" in pin_changes:
            causes.append("aeneas")
        if "lean" in pin_changes or "mathlib" in pin_changes:
            causes.append("lean-mathlib")
        if extraction and not extraction["comment_only"] and "rust" in groups:
            causes.append("rust")
        if set(pin_changes) - {"aeneas", "lean", "mathlib"}:
            causes.append("lean-dep")  # other lake dependency, e.g. PrimeCert
        if "extraction" in groups and not causes:
            # Re-extraction without a Rust or pin change: new functions extracted, config change...
            causes.append("extraction-config" if "extraction_config" in groups else "extraction-only")

        external_files = groups.get("external", [])
        proofs_in_change = miner.proof_summary(c["parent"], c["sha"], groups["proof"]) \
            if "proof" in groups else None

        # Follow-up fixes: commits after the trigger, before the next trigger, within limits.
        end = trigger_idx[t_pos + 1] if t_pos + 1 < len(trigger_idx) else len(commits)
        followups = []
        removed_by_change = set(proofs_in_change["theorems_removed"]) if proofs_in_change else set()
        sorry_by_change = set(proofs_in_change["sorry_added_in"]) if proofs_in_change else set()
        for j in range(i + 1, min(end, i + 1 + FOLLOWUP_MAX_COMMITS)):
            f = commits[j]
            if days_between(c["date"], f["date"]) > FOLLOWUP_MAX_DAYS:
                break
            fg = groups_by_sha[f["sha"]]
            if "proof" not in fg:
                continue
            reasons = []
            if FIX_MSG_RE.search(f["subject"]):
                reasons.append("message")
            ps = None
            if removed_by_change or sorry_by_change:
                ps = miner.proof_summary(f["parent"], f["sha"], fg["proof"])
                restored = removed_by_change & set(miner.lean_diff(f["parent"], f["sha"], fg["proof"])["added"])
                if restored:
                    reasons.append(f"restores {len(restored)} theorem(s) removed by change")
                cleared = sorry_by_change & set(ps["sorry_removed_in"])
                if cleared:
                    reasons.append(f"removes sorry from {len(cleared)} theorem(s) sorried by change")
            if reasons:
                ps = ps or miner.proof_summary(f["parent"], f["sha"], fg["proof"])
                followups.append({
                    "sha": f["sha"], "date": f["date"], "subject": f["subject"],
                    "pr": pr_number(f["subject"]), "reasons": reasons,
                    "proofs": {k: ps[k] for k in ("files_changed", "lines_added", "lines_removed",
                                                  "theorems_touched_n", "statements_changed_n",
                                                  "sorry_delta")},
                    "statements_changed": [s["name"] for s in ps["statements_changed"]],
                })

        fix_in_change = bool(proofs_in_change and (proofs_in_change["theorems_touched_n"]
                                                   or proofs_in_change["theorems_removed_n"]))
        stmt_names = [s["name"] for s in (proofs_in_change or {}).get("statements_changed", [])]
        for fu in followups:
            stmt_names += fu["statements_changed"]
        extraction_modifies = bool(extraction and not extraction["only_additions"])
        core_pin_change = bool({"aeneas", "lean", "mathlib"} & set(pin_changes))
        pr = pr_number(c["subject"])

        records.append({
            "case_id": f"{cfg_name}/{c['sha'][:8]}",
            "repo": cfg["github"],
            "base_commit": c["parent"],
            "change_commit": c["sha"],
            "change_date": c["date"],
            "change_subject": c["subject"],
            "change_pr": pr,
            "change_pr_url": f"https://github.com/{cfg['github']}/pull/{pr}" if pr else None,
            "cause": causes[0],
            "causes": causes,
            "pin_changes": pin_changes,
            "files_changed_by_class": {k: len(v) for k, v in sorted(groups.items())},
            "extraction": extraction,
            "external_changed": [f["path"] for f in external_files],
            "rust_files_changed_n": len(groups.get("rust", [])),
            "fix": {
                "in_change_commit": fix_in_change,
                "fix_commits": ([c["sha"]] if fix_in_change else []) + [fu["sha"] for fu in followups],
                "followups": followups,
            },
            "proofs_in_change_commit": proofs_in_change,
            # Heuristic: existing theorems the human edited, removed, or sorried while fixing.
            "broken_theorems_heuristic": cap(sorted(set(
                (proofs_in_change or {}).get("theorems_touched", [])
                + (proofs_in_change or {}).get("theorems_removed", [])
                + (proofs_in_change or {}).get("sorry_added_in", [])
            ) - {""})),
            "statements_changed_by_fix": bool(stmt_names),
            "statements_changed_by_fix_n": len(stmt_names),
            "size": {
                "extraction_lines": (extraction["lines_added"] + extraction["lines_removed"]) if extraction else 0,
                "proof_lines": ((proofs_in_change["lines_added"] + proofs_in_change["lines_removed"])
                                if proofs_in_change else 0)
                               + sum(fu["proofs"]["lines_added"] + fu["proofs"]["lines_removed"] for fu in followups),
                "theorems_touched": ((proofs_in_change or {}).get("theorems_touched_n", 0)
                                     + sum(fu["proofs"]["theorems_touched_n"] for fu in followups)),
            },
            # Worth replaying: something the proofs depend on changed and humans edited proofs.
            "likely_break": bool((extraction_modifies or core_pin_change) and (fix_in_change or followups)),
            "mined_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        })
    return records


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True, choices=sorted(REPO_CONFIGS))
    ap.add_argument("--repo", required=True, type=Path, help="path to an existing local clone")
    ap.add_argument("--rev", help="history to walk (default: the config's rev)")
    ap.add_argument("--out", type=Path, help="JSONL output path (default: stdout)")
    args = ap.parse_args()

    records = mine(args.repo.expanduser(), args.config, args.rev)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
    out = open(args.out, "w") if args.out else sys.stdout
    try:
        for r in records:
            out.write(json.dumps(r, ensure_ascii=False) + "\n")
    finally:
        if args.out:
            out.close()
    n_likely = sum(r["likely_break"] for r in records)
    print(f"{len(records)} trigger commits, {n_likely} likely breaks -> {args.out or 'stdout'}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

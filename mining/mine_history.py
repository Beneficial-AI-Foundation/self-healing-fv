# ---------------------------------------------------------------- git helpers

AENEAS_HEADER = "-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS"
HEAD_BYTES = 400  # enough for the Aeneas header and the file-kind line after it


class Git:
    def __init__(self, repo: Path):
        self.repo = repo
        self._blob_cache: dict[tuple[str, str], str | None] = {}
        self._head_cache: dict[str, str] = {}
        self._batch = None

    def blob_head(self, blob: str | None) -> str:
        """First bytes of a blob, via one persistent `git cat-file --batch` (cached by blob id)."""
        if not blob or set(blob) == {"0"}:
            return ""
        if blob not in self._head_cache:
            try:
                if self._batch is None or self._batch.poll() is not None:
                    self._batch = subprocess.Popen(["git", "-C", str(self.repo), "cat-file", "--batch"],
                                                   stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                                   stderr=subprocess.DEVNULL)
                self._batch.stdin.write(blob.encode() + b"\n")
                self._batch.stdin.flush()
                header = self._batch.stdout.readline().split()
                if len(header) < 3 or header[1] != b"blob":
                    self._head_cache[blob] = ""
                else:
                    data = self._batch.stdout.read(int(header[2]) + 1)  # content + trailing newline
                    self._head_cache[blob] = data[:HEAD_BYTES].decode("utf-8", "replace")
            except (BrokenPipeError, OSError, ValueError):
                self._batch = None  # the batch process died (e.g. on an unfetchable object)
                self._head_cache[blob] = ""
        return self._head_cache[blob]

    def run(self, *args: str) -> str:
        out = subprocess.run(
            ["git", "-C", str(self.repo), *args],
            check=True, capture_output=True, text=True, errors="replace",
        )
        return out.stdout

    def show(self, rev: str, path: str) -> str | None:
        key = (rev, path)
        if key not in self._blob_cache:
            try:
                self._blob_cache[key] = self.run("show", f"{rev}:{path}")
            except subprocess.CalledProcessError:
                self._blob_cache[key] = None  # file absent at rev
        return self._blob_cache[key]

    def first_parent_commits(self, rev: str) -> list[dict]:
        sep = "\x1f"
        fmt = sep.join(["%H", "%P", "%aI", "%an", "%s"])
        rows = []
        for line in self.run("log", "--first-parent", "--reverse", f"--format={fmt}", rev).splitlines():
            sha, parents, date, author, subject = line.split(sep, 4)
            rows.append({
                "sha": sha, "parent": parents.split()[0] if parents else None,
                "date": date, "author": author, "subject": subject,
            })
        return rows

    def body(self, sha: str) -> str:
        return self.run("log", "-1", "--format=%b", sha)

    def changed_files(self, parent: str | None, sha: str) -> list[dict]:
        """Name-status + numstat for parent..sha (with rename detection)."""
        if parent is None:
            parent = self.run("hash-object", "-t", "tree", "/dev/null").strip()  # empty tree
        status = {}
        for line in self.run("diff", "--name-status", "-M", parent, sha).splitlines():
            parts = line.split("\t")
            code = parts[0]
            if code.startswith("R"):
                status[parts[2]] = {"status": "R", "old_path": parts[1], "path": parts[2]}
            else:
                status[parts[1]] = {"status": code, "old_path": parts[1], "path": parts[1]}
        for line in self.run("diff", "--raw", "--abbrev=40", "-M", parent, sha).splitlines():
            meta, *paths = line.split("\t")
            old_mode, new_mode, old_blob, new_blob, _ = meta.lstrip(":").split()
            entry = status.get(paths[-1])
            if entry is not None:  # only regular files have readable contents (not submodules)
                entry["old_blob"] = old_blob if old_mode.startswith("100") else None
                entry["new_blob"] = new_blob if new_mode.startswith("100") else None
        for line in self.run("diff", "--numstat", "-M", parent, sha).splitlines():
            added, removed, path = line.split("\t", 2)
            if " => " in path:  # rename syntax: a/{x => y}/b or x => y
                m = re.match(r"(.*)\{(.*) => (.*)\}(.*)", path)
                path = (m.group(1) + m.group(3) + m.group(4)).replace("//", "/") if m else path.split(" => ")[1]
            entry = status.setdefault(path, {"status": "?", "old_path": path, "path": path})
            entry["added"] = int(added) if added != "-" else 0
            entry["removed"] = int(removed) if removed != "-" else 0
        return list(status.values())


def matches(path: str, globs: list[str]) -> bool:
    return any(fnmatch.fnmatch(path, g) for g in globs)


# ---------------------------------------------------------------- Lean parsing

def strip_comments(src: str) -> str:
    """Blank out Lean comments (nested block comments, line comments), keeping newlines."""
    out = []
    i, n, depth, in_str = 0, len(src), 0, False
    while i < n:
        c, nxt = src[i], src[i + 1] if i + 1 < n else ""
        if depth:
            if c == "/" and nxt == "-":
                depth += 1; out.append("  "); i += 2; continue
            if c == "-" and nxt == "/":
                depth -= 1; out.append("  "); i += 2; continue
            out.append("\n" if c == "\n" else " "); i += 1; continue
        if in_str:
            out.append(c)
            if c == "\\" and nxt:
                out.append(nxt); i += 2; continue
            if c == '"':
                in_str = False
            i += 1; continue
        if c == '"':
            in_str = True; out.append(c); i += 1; continue
        if c == "/" and nxt == "-":
            depth = 1; out.append("  "); i += 2; continue
        if c == "-" and nxt == "-":
            j = src.find("\n", i)
            j = n if j == -1 else j
            out.append(" " * (j - i)); i = j; continue
        out.append(c); i += 1
    return "".join(out)


DECL_RE = re.compile(
    r"^[ \t]*(?:@\[[^\]]*\][ \t]*)*"
    r"(?:(?:private|protected|noncomputable|partial|unsafe|nonrec)[ \t]+)*"
    r"(theorem|lemma|def|abbrev|instance|axiom|opaque|structure|inductive|class)\b[ \t]*"
    r"([^\s:({\[⦃]*)"
)
# Lines that end the previous declaration even though they are not declarations.
BOUNDARY_RE = re.compile(
    r"^(@\[|set_option\b|namespace\b|end\b|section\b|noncomputable section|open\b|variable\b|"
    r"attribute\b|#|universe\b|mutual\b|import\b|"
    # Lean module system (e.g. SPQR after #651): `module`, `public section`, `public import`.
    r"module\b|(?:public |private )(?:noncomputable )?section\b|(?:public |private |meta )+import\b)"
)
SECTION_RE = re.compile(r"^(?:@\[[^\]]*\]\s*)*(?:public |private )?(?:noncomputable )?section\b")
OPEN = "([{⦃⟨"
CLOSE = ")]}⦄⟩"


def split_statement(text: str) -> tuple[str, str]:
    """Split a declaration into (statement, body) at the first top-level ':=' / '|' / 'where'."""
    depth = 0
    binders = 0  # `let`/`have` inside the statement: their `:=` is not the declaration's
    i = 0
    while i < len(text):
        c = text[i]
        if c in OPEN:
            depth += 1
        elif c in CLOSE:
            depth = max(0, depth - 1)
        elif depth == 0:
            m = re.match(r"(let|have|letI|haveI)\b", text[i:i + 6])
            if m and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] in "_'.")):
                binders += 1
                i += len(m.group(1)); continue
            if text.startswith(":=", i):
                if binders:
                    binders -= 1
                    i += 2; continue
                return text[:i], text[i:]
            if c == "|" and (i == 0 or text[i - 1] == "\n" or text[:i].rstrip(" \t").endswith("\n")):
                return text[:i], text[i:]
            if text.startswith("where", i) and (i == 0 or not text[i - 1].isalnum()) and \
                    (i + 5 == len(text) or not (text[i + 5].isalnum() or text[i + 5] in "_'.")):
                return text[:i], text[i:]
        i += 1
    return text, ""


def norm(s: str) -> str:
    return " ".join(s.split())


def canon(s: str) -> str:
    """Comparison key: also drop whitespace next to punctuation, which Lean ignores
    (e.g. `(u : T): P` vs `(u : T) : P`)."""
    return re.sub(r" ?([^\w\s.'!?]) ?", r"\1", norm(s))


def split_header(stmt: str) -> tuple[str, str]:
    """Split leading `@[...]` attributes and `set_option ... in` off a normalized statement."""
    i = 0
    while True:
        rest = stmt[i:]
        m = re.match(r"set_option \S+ \S+ in ", rest)
        if m:
            i += m.end(); continue
        if rest.startswith("@["):
            depth, j, in_str = 0, 0, False
            while j < len(rest):
                ch = rest[j]
                if ch == '"':
                    in_str = not in_str
                elif not in_str and ch == "[":
                    depth += 1
                elif not in_str and ch == "]":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            i += j + 1
            while i < len(stmt) and stmt[i] == " ":
                i += 1
            continue
        return stmt[:i].strip(), stmt[i:]


def parse_decls(src: str | None) -> dict[str, dict]:
    """Map declaration name -> {kind, header, statement, body, sorry, start/body_start/end offsets,
    line/body_line/end_line (1-indexed)} from Lean source (comments ignored). Offsets index the
    original source, since comment stripping preserves length."""
    if src is None:
        return {}
    lines = strip_comments(src).split("\n")
    offsets, off = [], 0
    for line in lines:
        offsets.append(off); off += len(line) + 1
    decls: dict[str, dict] = {}
    cur = None

    def close():
        if cur is None:
            return
        idx = cur["idx"]
        while len(idx) > 1 and not lines[idx[-1]].strip():
            idx = idx[:-1]  # drop trailing blank lines
        text = "\n".join(lines[i] for i in idx)
        stmt, body = split_statement(text)
        header, statement = split_header(norm(stmt))
        name = cur["name"]
        if not name:  # name wrapped onto the next line, e.g. long Aeneas-generated names
            m = re.match(r"(?:(?:private|protected|noncomputable|partial|unsafe|nonrec) )*\w+ ([^\s:({\[⦃]+)", statement)
            name = m.group(1) if m and cur["kind"] != "instance" else f"<{cur['kind']}>:{statement[:80]}"
        key = name
        k = 2
        while key in decls:  # duplicate short names (e.g. in different namespaces)
            key = f"{name}#{k}"; k += 1
        start = offsets[idx[0]]
        body_start = start + len(stmt)
        body_line0 = idx[0] + stmt.count("\n")
        decls[key] = {
            "kind": cur["kind"], "header": header, "statement": statement, "body": norm(body),
            "sorry": len(re.findall(r"\b(sorry|admit)\b", text)),
            "start": start, "body_start": body_start, "end": start + len(text),
            "line": idx[0] + 1, "kw_line": cur["kw_line"], "body_line": body_line0 + 1, "body_col": body_start - offsets[body_line0],
            "end_line": idx[-1] + 1,
            "namespace": cur["ns"],  # enclosing `namespace` blocks, captured where the decl starts
        }

    pending: list[int] = []  # attribute / `set_option ... in` lines preceding a declaration
    ns_stack: list[str] = []  # namespace names; "" for an anonymous or named section
    for i, line in enumerate(lines):
        if line[:1] not in (" ", "\t", ""):
            mn = re.match(r"namespace\s+(\S+)", line)
            if mn:
                ns_stack.append(mn.group(1))
            elif SECTION_RE.match(line):
                ns_stack.append("")
            elif re.match(r"end\b", line) and ns_stack:
                ns_stack.pop()
        m = DECL_RE.match(line)
        if m:
            close()
            cur = {"kind": m.group(1), "name": m.group(2), "idx": pending + [i], "kw_line": i + 1,
                   "ns": ".".join(n for n in ns_stack if n)}
            pending = []
        elif line[:1] not in (" ", "\t", "") and BOUNDARY_RE.match(line):
            close(); cur = None
            # `@[expose] public section` opens a section; it is not an attribute of the next decl.
            prefix = (line.startswith("@[") and not SECTION_RE.match(line)) or \
                re.match(r"set_option\b.*\bin\s*$", line)
            pending = pending + [i] if prefix else []
        elif cur is not None:
            cur["idx"].append(i)
        elif pending:
            pending.append(i)  # continuation of a multi-line attribute, or a blank/comment line
    close()
    return decls


CONTEXT_RE = re.compile(r"^(namespace|open|section|end|variable|universe|export|"
                        r"(?:@\[[^\]]*\]\s*)*(?:public |private )(?:noncomputable )?section)\b.*$", re.M)


def context_lines(src: str | None) -> list[str]:
    """Non-declaration lines that change how names in a file resolve (namespace, open, ...)."""
    return [norm(m.group(0)) for m in CONTEXT_RE.finditer(strip_comments(src))] if src else []


def diff_decls(before: dict, after: dict) -> dict:
    added = sorted(set(after) - set(before))
    removed = sorted(set(before) - set(after))
    stmt_changed, body_changed, header_changed = [], [], []
    for name in sorted(set(before) & set(after)):
        b, a = before[name], after[name]
        if canon(b["statement"]) != canon(a["statement"]):
            stmt_changed.append(name)
        elif canon(b["body"]) != canon(a["body"]):
            body_changed.append(name)
        if canon(b["header"]) != canon(a["header"]):
            header_changed.append(name)  # attributes / set_option only, e.g. @[progress] -> @[step]
    return {"added": added, "removed": removed, "statement_changed": stmt_changed,
            "body_changed": body_changed, "header_changed": header_changed}


# ---------------------------------------------------------------- toolchain

def toolchain_pins(git: Git, rev: str | None, cfg: dict) -> dict:
    """Lean toolchain plus every lake-manifest package rev, keyed by package name ("lean" for
    the toolchain itself), read from the Lake project at cfg["lean_root"]."""
    if rev is None:
        return {}
    pins = {}
    tc = git.show(rev, lean_path(cfg, "lean-toolchain"))
    if tc is not None:
        pins["lean"] = tc.strip()
    manifest = git.show(rev, lean_path(cfg, "lake-manifest.json"))
    if manifest:
        try:
            for pkg in json.loads(manifest).get("packages", []):
                pins[pkg.get("name", "?")] = pkg.get("rev")
        except json.JSONDecodeError:
            pins["lake-manifest.json"] = "<unparseable>"
    if cfg.get("aeneas_pin"):
        m = re.search(cfg["aeneas_pin"]["regex"], git.show(rev, cfg["aeneas_pin"]["file"]) or "", re.M)
        pins[cfg["aeneas_package"]] = m.group(1) if m else None
    return pins


def lean_libs(lakefile_toml: str | None, lakefile_lean: str | None) -> list[tuple[str, str]]:
    """(lib name, srcDir) for each `lean_lib` in a lakefile (TOML or Lean DSL), best effort."""
    libs = []
    if lakefile_toml:
        for block in re.split(r"^\s*\[\[", lakefile_toml, flags=re.M)[1:]:
            if not block.startswith("lean_lib]]"):
                continue
            name = re.search(r'^\s*name\s*=\s*"([^"]+)"', block, re.M)
            src = re.search(r'^\s*srcDir\s*=\s*"([^"]+)"', block, re.M)
            if name:
                libs.append((name.group(1), src.group(1) if src else "."))
    if lakefile_lean:
        for m in re.finditer(r"^lean_lib\s+«?([\w.]+)»?(.*?)(?=^\S|\Z)", lakefile_lean, re.M | re.S):
            src = re.search(r'srcDir\s*:=\s*"([^"]+)"', m.group(2))
            libs.append((m.group(1), src.group(1) if src else "."))
    return libs


def module_resolver(libs: list[tuple[str, str]]):
    """Return f(path relative to the Lake project root) -> Lean module name, using the longest
    matching lean_lib srcDir (Lake resolves modules relative to srcDir, not the project root)."""
    dirs = sorted({src.strip("./") for _, src in libs} | {""}, key=len, reverse=True)

    def to_module(rel: str) -> str:
        rel = rel[2:] if rel.startswith("./") else rel
        for d in dirs:
            if not d or rel.startswith(d + "/"):
                rel = rel[len(d) + 1:] if d else rel
                break
        return rel[:-len(".lean")].replace("/", ".") if rel.endswith(".lean") else rel
    return to_module


